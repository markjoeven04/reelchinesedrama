"""Generates the ReelDrama mark: a vertical film-strip card with a play cutout.

Writes the Android adaptive-icon layers and an SVG logo. All shapes live on the
108x108 adaptive-icon canvas (visible area 18..90).
Usage: python3 tools/build_icon.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "reeldrama/android/app/src/main/res"
STOPS = [(0, "#29D3FF"), (0.5, "#2F6BFF"), (1, "#6E45F7")]


def rrect(x, y, w, h, r):
    return (f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0 1 {r},{r}v{h - 2 * r}a{r},{r} 0 0 1 -{r},{r}"
            f"h-{w - 2 * r}a{r},{r} 0 0 1 -{r},-{r}v-{h - 2 * r}a{r},{r} 0 0 1 {r},-{r}z")


# Card, five sprocket holes per side, play triangle. Even-odd fill turns the inner shapes into cutouts.
holes = [rrect(x, y, 4, 5, 1) for x in (39, 65) for y in (31, 41.5, 52, 62.5, 73)]
MARK = " ".join([rrect(36, 27, 36, 54, 7), *holes, "M49,45L62,54L49,63z"])

(RES / "drawable/ic_launcher_foreground.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build_icon.py. ReelDrama mark on the 108dp adaptive canvas. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"
        android:pathData="{MARK}"/>
</vector>
""")

(RES / "drawable/ic_launcher_background.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="18" android:startY="18"
                android:endX="90" android:endY="90">
                {"".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in STOPS)}
            </gradient>
        </aapt:attr>
    </path>
</vector>
""")

(RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text("""<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
""")

# Standalone logo: the visible 72x72 area with an iOS-style corner radius (~22%).
(ROOT / "reeldrama/assets/brand").mkdir(parents=True, exist_ok=True)
(ROOT / "reeldrama/assets/brand/logo.svg").write_text(f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="1024" height="1024">
  <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
    {"".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in STOPS)}</linearGradient></defs>
  <rect x="18" y="18" width="72" height="72" rx="16" fill="url(#g)"/>
  <path fill="#fff" fill-rule="evenodd" d="{MARK}"/>
</svg>
""")
print("ok")
